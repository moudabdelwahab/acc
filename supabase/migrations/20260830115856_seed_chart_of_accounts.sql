-- ربط الحسابات بالحساب الأب حسب بادئة الرمز
update public.accounts child
   set parent_id = parent.id
  from public.accounts parent
 where child.parent_id is null
   and parent.id <> child.id
   and parent.code = case
         when child.code ~ '^\d\d\d0$' and right(child.code, 2) <> '00'
           then left(child.code, 2) || '00'
         when child.code ~ '^\d\d00$' and right(child.code, 3) <> '000'
           then left(child.code, 1) || '000'
         else null
       end;

