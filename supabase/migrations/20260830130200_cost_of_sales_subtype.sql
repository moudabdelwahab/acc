-- ============================================================
-- قائمة الدخل تفصل «تكلفة المبيعات» عن المصروفات التشغيلية
-- اعتماداً على الحقل subtype، لكن حساب تكلفة البضاعة المباعة
-- كان مصنَّفاً «مصروفات» فكان قسم التكلفة يظهر فارغاً دائماً.
-- ============================================================

update public.accounts
   set subtype = 'تكلفة المبيعات'
 where code = '5100'
   and subtype is distinct from 'تكلفة المبيعات';
