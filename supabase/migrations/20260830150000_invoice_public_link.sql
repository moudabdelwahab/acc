-- ============================================================
-- الرابط العام للفاتورة (رمز QR)
--
-- الرمز تُصدره منصة مدعوم لا النظام المحاسبي: المنصة هي الجهة
-- التي تشهد بصحة الفاتورة، فهي مصدر الرمز. تكتبه المزامنة هنا
-- بعد تسجيل الفاتورة لدى المنصة، ليُطبع على الفاتورة كـ QR.
-- ============================================================

alter table public.invoices
  add column if not exists public_url   text,
  add column if not exists public_token text;

comment on column public.invoices.public_url is
  'رابط التحقق العام على منصة مدعوم — تكتبه دالة accounting-sync، لا الواجهة.';
